from __future__ import annotations

from contextlib import redirect_stdout
import hashlib
import io
import os
from pathlib import Path
import py_compile
import tempfile
import unittest
from unittest.mock import patch

from scripts import build_manifest as BUILD
from scripts import manifest_common as COMMON
from scripts import verify_manifest as VERIFY


class ManifestTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.addCleanup(self.folder.cleanup)
        self.root = Path(self.folder.name) / "bundle"
        self.root.mkdir()
        self.manifest = self.root / "MANIFEST.sha256"
        self.write("payload.txt", "reviewed bytes\n")
        self.build()

    def write(self, relative, content):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        return path

    def build(self):
        with patch.object(BUILD, "ROOT", self.root), patch.object(BUILD, "OUT", self.manifest), redirect_stdout(io.StringIO()):
            BUILD.main()

    def verify(self):
        with patch.object(VERIFY, "ROOT", self.root), patch.object(VERIFY, "MANIFEST", self.manifest), redirect_stdout(io.StringIO()):
            VERIFY.main()

    def fails_before_hash(self, message):
        with patch.object(VERIFY, "digest") as digest:
            with self.assertRaisesRegex(SystemExit, message):
                self.verify()
            digest.assert_not_called()

    def test_round_trip_is_deterministic(self):
        self.verify()
        original = self.manifest.read_bytes()
        self.build()
        self.assertEqual(self.manifest.read_bytes(), original)

    def test_unmanifested_source_cannot_hide_behind_directory_names(self):
        for relative in ("scripts/reproduction/audit_payload.py", "docs/reproduction/note.md",
                         "reproduction/payload.py", "scripts/__pycache__/payload.py",
                         ".pytest_cache/payload.py", "scripts/.pytest_cache/README.md",
                         "scripts/.git/payload.py", "scripts/__pycache__/orphan.cpython-314.pyc"):
            with self.subTest(relative=relative):
                path = self.write(relative, "synthetic fixture; never executed\n")
                self.fails_before_hash("unmanifested")
                path.unlink()

    def test_only_root_relative_recount_output_is_generated(self):
        self.write("output/reproduction/code_crosscheck.json", "{}\n")
        self.verify()
        self.write("nested/output/reproduction/code_crosscheck.json", "{}\n")
        self.fails_before_hash("unmanifested")

    def test_generated_bytecode_and_known_root_pytest_cache_are_allowed(self):
        source = self.write("scripts/helper.py", "value = 1\n")
        self.build()
        py_compile.compile(str(source), doraise=True)
        for relative in COMMON.PYTEST_FILES:
            self.write(relative, "synthetic generated cache metadata\n")
        self.verify()
        self.build()
        self.assertFalse(any("__pycache__" in line or ".pytest_cache" in line
                             for line in self.manifest.read_text().splitlines()))

    def test_tracked_cache_looking_files_remain_in_inventory(self):
        relative = ".pytest_cache/README.md"
        self.write(relative, "tracked source cannot disappear\n")
        with patch.object(COMMON, "tracked_paths", return_value={relative}):
            self.fails_before_hash("unmanifested")
            self.build()
            self.assertIn(relative, self.manifest.read_text())
            self.verify()

    def test_tracked_bytecode_looking_file_is_not_excluded(self):
        self.write("scripts/helper.py", "value = 1\n")
        self.build()
        relative = "scripts/__pycache__/helper.cpython-314.pyc"
        self.write(relative, "not generated bytecode\n")
        with patch.object(COMMON, "tracked_paths", return_value={relative}):
            self.fails_before_hash("unmanifested")

    def test_file_directory_and_generated_output_symlinks_are_rejected(self):
        outside = Path(self.folder.name) / "outside.txt"
        outside.write_text("outside sentinel\n")
        digest = hashlib.sha256(outside.read_bytes()).hexdigest()
        for relative, target in (("linked.txt", outside), ("linked-dir", outside.parent),
                                 ("output/reproduction/linked.txt", outside)):
            with self.subTest(relative=relative):
                link = self.root / relative
                link.parent.mkdir(parents=True, exist_ok=True)
                link.symlink_to(target)
                self.manifest.write_text(f"{digest}  {relative}\n")
                self.fails_before_hash("symlink")
                with patch.object(BUILD, "digest") as byte_hash:
                    with self.assertRaisesRegex(SystemExit, "symlink"):
                        self.build()
                    byte_hash.assert_not_called()
                link.unlink()
                self.build()

    @unittest.skipUnless(hasattr(os, "mkfifo"), "FIFO fixture requires POSIX")
    def test_non_regular_files_fail_without_opening_them(self):
        os.mkfifo(self.root / "payload.fifo")
        self.fails_before_hash("non-regular")
        with patch.object(BUILD, "digest") as digest:
            with self.assertRaisesRegex(SystemExit, "non-regular"):
                self.build()
            digest.assert_not_called()

    def test_missing_file_fails_before_any_payload_hash(self):
        (self.root / "payload.txt").unlink()
        self.fails_before_hash("missing")

    def test_missing_manifest_fails(self):
        self.manifest.unlink()
        self.fails_before_hash("MANIFEST_FAIL")

    def test_symlink_manifest_is_not_read(self):
        outside = Path(self.folder.name) / "outside-manifest"
        outside.write_bytes(self.manifest.read_bytes())
        self.manifest.unlink()
        self.manifest.symlink_to(outside)
        self.fails_before_hash("symlink")

    def test_malformed_and_duplicate_manifest_rows_fail_before_hashing(self):
        original = self.manifest.read_text()
        digest = original.split("  ", 1)[0]
        for text in ("", "not a hash  payload.txt\n", f"{digest} payload.txt\n",
                     original + "\n", original + original,
                     f"{digest.upper()}  payload.txt\n"):
            with self.subTest(text=text):
                self.manifest.write_text(text)
                self.fails_before_hash("MANIFEST_FAIL")

    def test_absolute_traversal_and_noncanonical_paths_fail_before_hashing(self):
        digest = self.manifest.read_text().split("  ", 1)[0]
        for relative in (str(Path(self.folder.name) / "outside.txt"), "../outside.txt",
                         "../../outside.txt", "scripts/../payload.txt", "./payload.txt",
                         "scripts//payload.txt", "C:/outside.txt", "C:\\outside.txt"):
            with self.subTest(relative=relative):
                self.manifest.write_text(f"{digest}  {relative}\n")
                self.fails_before_hash("unsafe manifest path")

    def test_hash_mismatch_fails(self):
        self.write("payload.txt", "changed reviewed bytes\n")
        with self.assertRaisesRegex(SystemExit, "hash mismatch"):
            self.verify()


if __name__ == "__main__":
    unittest.main()
